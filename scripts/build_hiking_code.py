"""Generate the website's highlighted excerpts from the actual Blender source.

Run this after editing a # demo:start / # demo:end section in the renderer.
No Blender installation or video re-render is needed for this build step.
"""
import io
import json
import keyword
from pathlib import Path
import tokenize

root = Path(__file__).resolve().parents[1]
source = root / 'scripts/render_hiking_stylized.py'
text = source.read_text()
source_lines = text.splitlines()
all_tokens = list(tokenize.generate_tokens(io.StringIO(text).readline))


def excerpt(name):
    start = next(i for i, line in enumerate(source_lines) if line.strip() == f'# demo:start {name}') + 1
    end = next(i for i, line in enumerate(source_lines[start:], start) if line.strip() == f'# demo:end {name}')
    indentation = min(len(line) - len(line.lstrip()) for line in source_lines[start:end] if line.strip())
    result = []
    for row in range(start, end):
        line = source_lines[row]
        pieces, cursor = [], indentation
        for token in all_tokens:
            if token.start[0] != row + 1 or token.end[0] != row + 1:
                continue
            kind = {tokenize.STRING: 'str', tokenize.NUMBER: 'num', tokenize.COMMENT: 'comment'}.get(token.type)
            if token.type == tokenize.NAME and keyword.iskeyword(token.string):
                kind = 'kw'
            if not kind:
                continue
            begin, finish = token.start[1], token.end[1]
            if begin > cursor:
                pieces.append({'text': line[cursor:begin], 'kind': ''})
            pieces.append({'text': line[begin:finish], 'kind': kind})
            cursor = finish
        if cursor < len(line):
            pieces.append({'text': line[cursor:], 'kind': ''})
        assert ''.join(piece['text'] for piece in pieces) == line[indentation:]
        result.append({'number': row + 1, 'tokens': pieces})
    return result


chapters = [
    ('snow', 0, 3, 'Snow', '01 / Build the snow terrain',
     'Python geometry → the snowfield underfoot',
     'box() creates the mesh; its material and slope define the snow trail.', ['imports', 'snow']),
    ('gait', 3, 6, 'Gait', '02 / Animate the hiking character',
     'Inverse kinematics → planted feet + bending knees',
     'solve_joint() computes the knee; the leg meshes follow the solved pose.', ['gait']),
    ('camera', 6, 9, 'Camera', '03 / Move the world past the camera',
     'Perspective + world motion → mountain parallax',
     'The same world-space speed projects to slower motion for distant ridges.', ['camera', 'parallax']),
    ('render', 9, 12, 'Render', '04 / Render the animation in Blender',
     'Python → Blender Cycles → the video you see',
     'render_frame() poses the scene; Cycles writes each of the 288 frames.', ['engine', 'render']),
]
data = {'fps': 24, 'frames': 288, 'source': 'scripts/render_hiking_stylized.py', 'chapters': []}
for name, start, end, label, title, caption, description, groups in chapters:
    lines = []
    for group in groups:
        lines.extend(excerpt(group))
    data['chapters'].append(dict(id=name, start=start, end=end, label=label, title=title,
                                 caption=caption, description=description, lines=lines))
(root / 'hiking-code.js').write_text('// Generated by scripts/build_hiking_code.py; do not edit by hand.\n'
                                    + 'window.HIKING_CODE = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n')
print('Built 4 source-backed code chapters.')
